"""Feasibility-aware orbital-chain permutations, multi-phase timing and suffix repair.

Actual ΔV queries always go to the original ESA/PyKEP compute_transfer.
No surrogate is allowed to validate a record. Search is heuristic, not a lower bound.
"""
from __future__ import annotations
from dataclasses import dataclass
from collections import OrderedDict
import math
import random
import time


@dataclass
class Stats:
    calls: int = 0
    cache_hits: int = 0
    trials: int = 0
    feasible_windows: int = 0
    complete_routes: int = 0
    distinct_routes: int = 0
    records: int = 0


class DVCache:
    def __init__(self, udp, limit=80000):
        self.udp, self.limit = udp, limit
        self.memo = OrderedDict()
        self.stats = Stats()
    def cost(self, a, b, t, tof):
        if tof < self.udp.min_tof - 1e-10 or t < -1e-9 or t+tof > self.udp.max_time+1e-9:
            return float('inf')
        key = (int(a),int(b),round(float(t),8),round(float(tof),8))
        if key in self.memo:
            self.stats.cache_hits += 1
            self.memo.move_to_end(key)
            return self.memo[key]
        try:
            val = float(self.udp.compute_transfer(*key))
        except Exception:
            val = float('inf')
        self.stats.calls += 1
        self.memo[key] = val
        if len(self.memo) > self.limit:
            self.memo.popitem(last=False)
        return val
    def exception(self, a, b, t, tof):
        val = self.cost(a,b,t,tof)
        if not math.isfinite(val) or val > self.udp.dv_threshold_exception + 1e-6:
            return None
        return int(val > self.udp.dv_threshold)


def group(a, semi_major_axes):
    return int(semi_major_axes[a] > 8e6)


def mandatory_shell_crossings(route, semi_major_axes):
    """Heuristic reserve for the energetically expensive inner/outer shell links.

    The official evaluator remains the only validity authority. A hypothetical
    normal-budget crossing is not generated by this heuristic.
    """
    n=len(route)-1
    suffix=[0]*(n+1)
    for i in range(n-1,-1,-1):
        suffix[i]=suffix[i+1]+int(group(route[i],semi_major_axes)!=group(route[i+1],semi_major_axes))
    return suffix


def mutation_order(route, rng, semi_major_axes, mode):
    """Topology moves that respect shell budgets more often than random global swaps."""
    n = len(route)
    if mode == 'crossing':
        boundaries = [i for i in range(1,n-1) if group(route[i], semi_major_axes)!=group(route[i+1],semi_major_axes)]
        if not boundaries:
            return None
        mid = rng.choice(boundaries)
        left = max(0,mid-rng.randint(2,5)); right = min(n-1, mid+rng.randint(2,5))
        # Change only order WITHIN each shell to keep the number of crossings stable.
        new = route[:]
        for shell in (0,1):
            inds = [j for j in range(left+1,right) if group(new[j],semi_major_axes)==shell]
            if len(inds)>1:
                a,b = sorted(rng.sample(inds,2))
                new[a],new[b] = new[b],new[a]
        if new == route: return None
        return left, right, new
    # Avoid most crossings, so we can reuse the prefix, exception budget and suffix.
    boundaries = [0] + [i+1 for i in range(n-1) if group(route[i],semi_major_axes)!=group(route[i+1],semi_major_axes)] + [n]
    sections = [(a,b) for a,b in zip(boundaries,boundaries[1:]) if b-a >= 5]
    if not sections:
        return None
    # Bias sections with long high-shell travel, but sample all sections.
    a,b = rng.choices(sections,weights=[(b-a)**0.65 for a,b in sections],k=1)[0]
    l = rng.randint(a,b-4)
    r = min(b-1,l+rng.randint(3,9))
    if r-l < 3: return None
    new=route[:]
    interior=new[l+1:r]
    op=rng.choice(['swap','insert','reverse','shuffle']) if mode=='diversify' else rng.choice(['swap','insert','reverse'])
    if op=='swap':
        i,j=sorted(rng.sample(range(len(interior)),2)); interior[i],interior[j]=interior[j],interior[i]
    elif op=='insert':
        i,j=rng.sample(range(len(interior)),2); x=interior.pop(i); interior.insert(j,x)
    elif op=='reverse':
        i,j=sorted(rng.sample(range(len(interior)),2)); interior[i:j+1]=reversed(interior[i:j+1])
    else: rng.shuffle(interior)
    new[l+1:r]=interior
    if new==route: return None
    return l,r,new


def departure_candidates(arrival, reference, rng, width=0.75, cap=18, source_reference=None):
    # More than one orbital phase is retained; earliest possible is not necessarily best.
    offsets=[0,.0625,.125,.1875,.25,.375,.5,.75,1.,1.5,2.]
    positions=[arrival+x for x in offsets] + [reference+x for x in
              (-2.,-1.5,-1.,-.75,-.5,-.25,-.125,-.0625,0.,.0625,.125,.25,.5)]
    positions += [arrival+rng.random()*width, reference+rng.uniform(-width,width)]
    # New ordering can move a tomato to a different index. Search its original
    # departure phase too, not just the old schedule at this index.
    if source_reference is not None:
        positions.extend(source_reference+x for x in (-1.9,-1.,-.5,-.125,0,.125,.5,1.,1.9))
    possibilities = sorted({round(v,8) for v in positions if v>=arrival-1e-8 and v>=0})
    if len(possibilities)>cap:
        # Include timing near arrival and reference as well as late orbital phases.
        ranked=sorted(possibilities,key=lambda x:(min(abs(x-arrival),abs(x-reference)),x))
        possibilities=sorted(ranked[:cap])
    return possibilities


def flight_candidates(reference, rng, cap=23):
    base=[.0625,.125,.1875,.25,.375,.5,.75,1.,1.5,2.,2.5,3.,3.5,4.,4.5,5.]
    alt=[reference, reference*.7,reference*.85,reference*1.1]
    alt += [reference+v for v in (-1.,-.5,-.25,-.125,-.0625,.0625,.125,.25,.5)]
    alt += [max(.0625,reference+rng.uniform(-.35,.35))]
    v=sorted({round(x,8) for x in base+alt if .01<=x<=6.5})
    if len(v)>cap:
        v=sorted(sorted(v,key=lambda x:(min(abs(x-reference),abs(x-.25),abs(x-1.0)),x))[:cap])
    return v


def select_beam(items, width, rng):
    """Keep early arrivals and a diverse set of arrival phases and exception budgets."""
    items.sort(key=lambda s:(s[0]+.18*s[1],s[0]))
    seen=set(); pool=[]
    for state in items:
        key=(int(state[0]*4),state[1]);
        if key in seen: continue
        seen.add(key);pool.append(state)
    if len(pool)<=width: return pool
    elite=pool[:max(1,int(width*.6))]
    rest=pool[max(1,int(width*.6)):]
    rng.shuffle(rest)
    # Diverse mid/late orbital phases are occasionally necessary for downstream edges.
    return sorted(elite+rest[:width-len(elite)],key=lambda x:(x[0],x[1]))


def beam_block(udp, cache, source_order, candidate_order, dep, tof, left, right,
               rng, *, beam=6, deadline=None, eval_limit=12000):
    """Schedule edges [left,right) for alternative order, holding prefix unchanged.

    The right node is reached by the final edge; the old suffix can be reused
    if the new arrival is before the reference departure at the right node.
    """
    n=len(dep)
    if left < 0 or right>n or not (left<right): return []
    prev=dep[left-1]+tof[left-1] if left else 0.
    earlier_ex=sum((cache.exception(source_order[i],source_order[i+1],dep[i],tof[i]) or 0)
                   for i in range(left))
    if earlier_ex>udp.n_dv_exception: return []
    old_departure_by_source={source_order[i]:dep[i] for i in range(n)}
    states=[(prev,earlier_ex,[],[])]
    # All five baseline exceptions connect different radius shells. Reserve
    # future shell crossings to avoid spending the exception budget too early.
    axes=[float(x[0]) for x in udp.tomato_orbital_parameters]
    required_future=mandatory_shell_crossings(candidate_order,axes)
    used_calls=cache.stats.calls
    max_clock=min(float(udp.max_time),dep[min(right,n-1)]+2.5)
    for i in range(left,right):
        if deadline and time.monotonic()>deadline: return []
        if cache.stats.calls - used_calls >=eval_limit: return []
        successors=[]
        a,b=candidate_order[i:i+2]
        for arrive,ex,dout,fout in states:
            dt=departure_candidates(arrive,dep[i],rng,cap=14,
                         source_reference=old_departure_by_source.get(a))
            flights=flight_candidates(tof[i],rng,cap=19)
            for start in dt:
                if start > max_clock: continue
                for flight in flights:
                    end=start+flight
                    if end>max_clock+1e-9: continue
                    e=cache.exception(a,b,start,flight)
                    if e is None or ex+e+required_future[i+1]>udp.n_dv_exception: continue
                    successors.append((end,ex+e,dout+[start],fout+[flight]))
            if cache.stats.calls - used_calls >=eval_limit: break
        if not successors: return []
        states=select_beam(successors,beam,rng)
    return states


def greedy_suffix(udp, cache, new_order, baseline_dep, baseline_tof,
                  left, arrival, used, rng, *, horizon=200, deadline=None):
    """Retimes entire remaining suffix with exact ESA ΔV, preserving a fallback.

    Bounded coordinate search, not proof of optimality. At every edge the known
    baseline transfer is a feasible fallback when chronology allows it.
    """
    n=len(baseline_dep)
    out_d=[];out_f=[]
    axes=[float(x[0]) for x in udp.tomato_orbital_parameters]
    required_future=mandatory_shell_crossings(new_order,axes)
    for i in range(left,n):
        if deadline and time.monotonic()>deadline: return None
        a,b=new_order[i],new_order[i+1]
        best=None
        # The original scheduled leg is always considered if it can be reached.
        if arrival<=baseline_dep[i]+1e-9:
            e=cache.exception(a,b,baseline_dep[i],baseline_tof[i])
            if e is not None and used+e+required_future[i+1]<=udp.n_dv_exception:
                best=(baseline_dep[i]+baseline_tof[i],baseline_dep[i],baseline_tof[i],e)
        # Shift departure windows and search shorter transfer durations.
        choices=departure_candidates(arrival,baseline_dep[i],rng,cap=10)
        flights=flight_candidates(baseline_tof[i],rng,cap=17)
        for d in choices:
            if d>baseline_dep[i]+.75: continue
            for f in flights:
                end=d+f
                if best and end>=best[0]-1e-8:continue
                e=cache.exception(a,b,d,f)
                if e is None or used+e+required_future[i+1]>udp.n_dv_exception:continue
                best=(end,d,f,e)
        if best is None:return None
        arrival, d, f, e=best
        out_d.append(d);out_f.append(f);used+=e
    return out_d,out_f,arrival


def try_mutation(udp, cache, sol, axes, rng, mode, *, beam=6, deadline=None):
    original=sol['path']; dep=sol['dep'];tof=sol['tof']
    move=mutation_order(original,rng,axes,mode)
    if move is None:return None
    l,r,new_order=move
    block=beam_block(udp,cache,original,new_order,dep,tof,l,r,rng,beam=beam,deadline=deadline)
    if not block:return None
    options=[]
    for arrival,used,ds,fs in block:
        # Need to reach the unchanged suffix. Search a few delayed arrivals too.
        if r < len(dep) and arrival>dep[r]+.9: continue
        options.append((arrival,used,ds,fs))
    if not options:return None
    # Rank feasible alternatives primarily by earlier arrival, retain diversity.
    options=select_beam(options,min(beam,len(options)),rng)
    for arrival,used,ds,fs in options:
        left_dep=dep[:l]+ds;left_tof=tof[:l]+fs
        # Validate the modified prefix; future exceptions already tracked in 'used'.
        if r==len(dep):
            cand={'path':new_order,'dep':left_dep,'tof':left_tof}
            return cand
        # When a modified block arrives earlier, attempt to advance ALL subsequent
        # scheduled legs, not only the next one.
        suffix=greedy_suffix(udp,cache,new_order,dep,tof,r,arrival,used,rng,deadline=deadline)
        if suffix:
            sd,sf,_=suffix
            return {'path':new_order,'dep':left_dep+sd,'tof':left_tof+sf}
    return None


def try_retime(udp,cache,sol,rng,deadline=None):
    dep=sol['dep'];tof=sol['tof'];order=sol['path']
    start=rng.choice([0,0,0,10,20,30,40,60,80,100,125,140])
    start=min(start,len(dep)-1)
    used=sum(cache.exception(order[i],order[i+1],dep[i],tof[i]) or 0 for i in range(start))
    arrive=dep[start-1]+tof[start-1] if start else 0.
    suffix=greedy_suffix(udp,cache,order,dep,tof,start,arrive,used,rng,deadline=deadline)
    if not suffix:return None
    sd,sf,_=suffix
    return {'path':order[:],'dep':dep[:start]+sd,'tof':tof[:start]+sf}


def score(sol):
    return sol['dep'][-1]+sol['tof'][-1]
